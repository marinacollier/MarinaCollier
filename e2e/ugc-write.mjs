// UGC Entrega 2 in a real browser (iPhone 13): brand → "já usou?" → strategy → Gerar DM → edit → Mandei →
// contact logged; Lumos "gera uma DM pra X"; nothing is sent by the app.
import { createRequire } from 'module'
import fs from 'fs'
const require = createRequire(new URL('../package.json', import.meta.url))
const { chromium, devices } = require('playwright')
const base = 'http://localhost:4310'
const dir = new URL('./.profiles/profile-ugc-write', import.meta.url).pathname
const shots = new URL('./.shots/', import.meta.url).pathname
fs.rmSync(dir, { recursive: true, force: true })
fs.mkdirSync(shots, { recursive: true })
const log = (...a) => console.log(...a)
const ctx = await chromium.launchPersistentContext(dir, { ...devices['iPhone 13'], permissions: ['clipboard-read', 'clipboard-write'] })
const page = ctx.pages()[0] ?? (await ctx.newPage())
page.on('pageerror', (e) => log('PAGEERROR', e.message))
await page.goto(base + '/')
await page.waitForTimeout(2000)
const enter = page.getByRole('button', { name: /Entrar no meu dia/i })
if (await enter.count()) { await enter.click(); await page.waitForTimeout(800) }
await page.goto(base + '/trabalho/creator/ugc')
await page.waitForTimeout(1200)
await page.getByLabel('Nome da marca').first().fill('Galápagos')
await page.getByRole('button', { name: 'Adicionar' }).first().click()
await page.waitForTimeout(800)
await page.locator('input[id^="b-cat-"]').fill('Outdoor')
await page.locator('input[id^="b-cat-"]').blur()
await page.waitForTimeout(400)
const w = page.locator('section[aria-label="Escrever abordagem"]')
log('asks first:', (await w.innerText()).includes('você já usou Galápagos?'))
await w.getByRole('button', { name: 'Nunca usei' }).click()
await page.waitForTimeout(400)
log('strategy:', (await w.locator('dl').innerText()).replace(/\n/g, ' | '))
await w.getByRole('button', { name: /^Gerar DM$/ }).click()
await page.waitForTimeout(800)
const text = await w.getByLabel('Mensagem').inputValue()
log('draft:\n' + text)
await page.screenshot({ path: shots + 'ugc-write.png', fullPage: true })
await w.getByRole('button', { name: 'Copiar' }).click()
await page.waitForTimeout(400)
log('status after copy:', (await w.innerText()).match(/· (rascunho|aprovada|enviada)/)?.[1])
await w.getByRole('button', { name: 'Mandei' }).click()
await page.waitForTimeout(600)
log('history:', (await page.locator('section[aria-label="Histórico"]').innerText()).split('\n').slice(1, 3).join(' | '))
await page.goto(base + '/trabalho/creator/ugc?aba=abordagens')
await page.waitForTimeout(1000)
log('abordagens:', (await page.locator('main').innerText()).split('\n').filter((l) => /Galápagos|primeiro/.test(l)).slice(0, 2).join(' | '))
await page.goto(base + '/')
await page.waitForTimeout(1200)
const box = page.getByLabel(/^Fal[ae] com a Lumos$/).last()
await box.fill('gera um email pra Galápagos')
await box.press('Enter')
await page.waitForTimeout(1500)
await page.screenshot({ path: shots + 'ugc-write-lumos.png', fullPage: true })
log('lumos:', (await page.getByText(/Rascunho de E-mail pra Galápagos|Rascunho de .* pra Galápagos/).first().textContent().catch(() => 'NO'))?.trim())
await ctx.close()
