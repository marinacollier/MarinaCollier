const TODAY = '2026-10-29' // Thursday, in Cape Town
const TRIP = SEED_IDS.tripAfrica
const STAMP = '2026-10-20T12:00:00.000Z'
const LATER = '2026-10-28T19:00:00.000Z'

const wo = (id: string, date: string, extra: Partial<Workout> = {}): Workout => ({ id, date, modality: 'natacao', status: 'planejado', order: 0, createdAt: STAMP, updatedAt: STAMP, ...extra })

/** Her real DB on 29/10: the seed + what she logged in Cape Town + an old generated base workout per week. */
function herDB(patch: (db: DB) => DB = (d) => d): DB {
  const db = buildSeed(TODAY)
  db.workouts = [
    ...db.workouts,
    // logged in Cape Town (Lumos / Corpo): never touched
    wo('w-surf-28', '2026-10-28', { modality: 'surf', status: 'feito', notes: 'Surf em Muizenberg · amei', createdAt: LATER, updatedAt: LATER }),
    wo('w-lions-28', '2026-10-28', { modality: 'trilha', status: 'feito', title: "Lion's Head", createdAt: LATER, updatedAt: LATER }),
    // generated by "Trazer a base da semana" before she left (random id, templateId), still untouched
    wo('w-base-27', '2026-10-27', { modality: 'musculacao', templateId: 'seed:body:tpl-ter-upper-pliometria' }),
    // a generated one she edited (moved the time) — hers now
    wo('seed:body:w-2026-11-04-tpl-qua-pernas', '2026-11-04', { modality: 'musculacao', templateId: 'seed:body:tpl-qua-pernas', time: '17:00', updatedAt: LATER }),
    // generated one marked feito on a trip day — never removed
    wo('seed:body:w-2026-10-25-tpl-dom-pedal-longo', '2026-10-25', { modality: 'bike', templateId: 'seed:body:tpl-dom-pedal-longo', status: 'feito' }),
    // after the trip: untouched generated workout stays
    wo('seed:body:w-2026-11-18-tpl-qua-pernas', '2026-11-18', { modality: 'musculacao', templateId: 'seed:body:tpl-qua-pernas' }),
  ]
  return patch(db)
}

const ready = (patch?: (db: DB) => DB) => applyModuleSeeds(herDB(patch))
const trip = (db: DB) => db.trips.find((t) => t.id === TRIP)!
const withTrip = (db: DB, p: Partial<Trip>): DB => ({ ...db, trips: db.trips.map((t) => (t.id === TRIP ? { ...t, ...p } : t)) })

describe('modo viagem — which days', () => {
  it('covers the expedition dates (inclusive) and nothing else', () => {
    const db = ready()
    expect(trip(db).expedition).toBeDefined()
    expect(isTravelDay(db, '2026-10-23')).toBe(false)
    expect(isTravelDay(db, '2026-10-24')).toBe(true)
    expect(isTravelDay(db, TODAY)).toBe(true)
    expect(isTravelDay(db, '2026-11-16')).toBe(true)
    expect(isTravelDay(db, '2026-11-17')).toBe(false)
    // a trip only dreamed of never pauses anything
    expect(isTravelDay({ trips: [{ ...trip(db), expedition: undefined, status: 'sonhando' }] }, TODAY)).toBe(false)
    expect(travelModeLine(trip(db))).toBe('Modo viagem ativo: rotina de SP pausada até 16/11')
  })

  it('she can turn it off per trip (pauseHomeRoutine = false)', () => {
    const off = withTrip(ready(), { pauseHomeRoutine: false })
    expect(travelTripOn(off, TODAY)).toBeUndefined()
    expect(isPresencial(off, '2026-10-28')).toBe(true)
    expect(routineItemsFor(off, SEED_IDS.routineMorning, TODAY).length).toBeGreaterThan(0)
  })
})

describe('treinos', () => {
  it('removes only untouched generated template workouts on trip days; keeps everything she logged or edited', () => {
    const db = ready()
    const ids = db.workouts.map((w) => w.id)
    // the seed generated 29/10, 30/10 and 01/11 — all trip days → gone
    expect(ids.filter((id) => /^seed:body:w-2026-1[01]-(29|30|01)-/.test(id))).toEqual([])
    expect(ids).not.toContain('w-base-27')
    for (const keep of ['w-surf-28', 'w-lions-28', 'seed:body:w-2026-11-04-tpl-qua-pernas', 'seed:body:w-2026-10-25-tpl-dom-pedal-longo', 'seed:body:w-2026-11-18-tpl-qua-pernas']) expect(ids).toContain(keep)
    // a seed migration never brings the removed seed ones back
    expect(db.profile.removedSeedIds).toEqual(expect.arrayContaining(['seed:body:w-2026-10-29-tpl-qui-natacao', 'seed:body:w-2026-10-30-tpl-sex-corrida-longa']))
  })

  it('is idempotent and deterministic', () => {
    const once = ready()
    expect(pruneTravelWorkouts(once)).toBe(once)
    expect(applyModuleSeeds(once)).toBe(once)
    expect(ready().workouts.map((w) => w.id)).toEqual(once.workouts.map((w) => w.id))
  })

  it('the weekly template proposes nothing on trip days and resumes after 16/11', () => {
    const db = ready()
    expect(proposeWeekFromTemplate(db, '2026-10-26')).toEqual([])
    expect(materializeWeek(db, '2026-10-26', TODAY)).toEqual([])
    // the week of 16/11: Monday is still the trip (flight home), the rest is São Paulo again
    const back = proposeWeekFromTemplate(db, '2026-11-16')
    expect(back.length).toBeGreaterThan(0)
    expect(back.every((p) => p.date > '2026-11-16')).toBe(true)
    expect(contextWorkouts(db, '2026-10-30')).toEqual([])
    expect(contextWorkouts(db, '2026-11-20').map((w) => w.title)).toContain('Corrida longa Z2')
    // no São Paulo windows suggested for yoga during the trip
    expect(suggestWindows(db, { modality: 'yoga', from: TODAY }).every((s) => !isTravelDay(db, s.date))).toBe(true)
  })

  it("what she logged on a trip day still shows as that day's training", () => {
    const db = ready()
    expect(contextWorkouts(db, '2026-10-28').map((w) => w.id).sort()).toEqual(['w-lions-28', 'w-surf-28'])
  })
})

describe('trabalho', () => {
  it('no commute, no work block, no presencial on trip days — back after the trip', () => {
    const db = ready()
    expect(workMode(db, '2026-10-28')).toBe('off') // a Wednesday (presencial in SP)
    expect(workBlocks(db, '2026-10-28')).toEqual([])
    expect(agendaFor(db, '2026-10-28', { includeBlocks: true }).some((e) => e.blockKind === 'commute' || e.blockKind === 'work')).toBe(false)
    expect(dayTimeline(db, '2026-10-28').some((e) => e.kind === 'work')).toBe(false)
    expect(prepChecklistFor(db, '2026-10-27')).toEqual([])
    const m = morningRoutine(db)!
    expect(essentialSuggestion(db, m, '2026-10-28')).toBeUndefined()
    // 18/11, a Wednesday back home
    expect(workMode(db, '2026-11-18')).toBe('presencial')
    expect(workBlocks(db, '2026-11-18').map((b) => b.kind)).toEqual(['commute', 'work', 'commute'])
  })

  it('the expedition class takes the place of the work hours', () => {
    const db = ready()
    const school = agendaFor(db, TODAY, { includeBlocks: true }).find((e) => e.blockKind === 'school')
    expect(school).toMatchObject({ time: '09:00', endTime: '15:10', title: 'Aula · Bayswater Cape Town' })
    expect(agendaFor(db, '2026-10-30', { includeBlocks: true }).find((e) => e.blockKind === 'school')?.endTime).toBe('12:20')
    // a planned whole-day absence (Gansbaai, 05/11) → no class row
    expect(agendaFor(db, '2026-11-05', { includeBlocks: true }).some((e) => e.blockKind === 'school')).toBe(false)
  })
})

describe('rotinas e vida local', () => {
  it('Milagre da Manhã and Encerrar o dia pause on trip days (not deleted) and resume on 17/11', () => {
    const db = ready()
    const before = db.routineItems.length
    for (const r of [SEED_IDS.routineMorning, EVENING_ROUTINE_ID]) {
      expect(routineItemsFor(db, r, TODAY)).toEqual([])
      expect(routineItemsFor(db, r, '2026-11-16')).toEqual([])
      expect(routineItemsFor(db, r, '2026-11-17').length).toBeGreaterThan(0)
    }
    expect(db.routineItems.length).toBe(before)
    expect(db.routines.every((r) => r.active)).toBe(true)
    const tl = dayTimeline(db, TODAY)
    expect(tl.some((e) => e.kind === 'routineItem')).toBe(false)
    expect(dayTimeline(db, '2026-11-17').some((e) => e.kind === 'routineItem')).toBe(true)
    // no occurrences are ever written for the paused days
    expect(db.occurrences.some((o) => o.date >= '2026-10-24' && o.date <= '2026-11-16' && o.parentType === 'routineItem')).toBe(false)
  })

  it('Luna, meal plan and recurring local events pause; a one-off event she created stays', () => {
    const db = ready((d) => ({
      ...d,
      events: [...d.events, { id: 'ev-call', sourceId: SEED_IDS.sourceLocal, title: 'Call com a mãe', date: TODAY, startTime: '19:00', allDay: false, createdAt: STAMP, updatedAt: STAMP } as DB['events'][number]],
    }))
    expect(petTasksDue(db, TODAY)).toEqual([])
    expect(dayPlanFor(db, TODAY)).toBeUndefined()
    const titles = eventsFor(db, TODAY).map((e) => e.title)
    expect(titles).toContain('Call com a mãe')
    expect(titles).not.toContain('Cerâmica') // Mon/Thu in São Paulo
    expect(eventsFor(db, '2026-10-30').map((e) => e.title)).not.toContain('Fisioterapia')
    expect(eventsFor(db, '2026-10-31').map((e) => e.title)).not.toContain('Weekly CEO Review')
    expect(eventsFor(db, '2026-11-19').map((e) => e.title)).toContain('Cerâmica')
  })
})

describe('Home rows on a trip day', () => {
  it('the class and the trip activities replace the São Paulo routine', () => {
    const db = ready()
    const items = dayItems(db, '2026-10-28', '2026-10-28')
    const titles = items.map((i) => i.title)
    expect(titles).toContain('Aula · Bayswater Cape Town')
    expect(titles.some((t) => /Lion's Head/.test(t))).toBe(true)
    expect(titles).not.toContain('Milagre da Manhã')
    expect(titles).not.toContain('Encerrar o dia')
    expect(items.some((i) => i.front.label === 'ROTINA')).toBe(false)
    expect(items.some((i) => i.refType === 'petTask')).toBe(false)
    // back home: the routine is there again
    expect(dayItems(db, '2026-11-17', '2026-11-17').map((i) => i.title)).toContain('Milagre da Manhã')
  })
})

// ─── Cloud sync: removal travels as an ordinary delete, never resurrected ───

function device(server: ReturnType<typeof createFakePostgrest>, initial: DB) {
  let db = structuredClone(initial)
  let clock = Date.parse('2026-10-29T12:00:00Z')
  const store = { meta: null as SyncMeta | null }
  const engine = createSyncEngine({
    api: createRecordsApi({ baseUrl: 'https://ref.supabase.co', anonKey: 'anon', token: async () => server.tokenFor('u1'), fetchImpl: server.fetch, pageSize: 50, pushBatch: 50 }),
    meta: { load: async () => (store.meta ? structuredClone(store.meta) : null), save: async (m) => void (store.meta = structuredClone(m)) },
    getDB: () => db,
    commitDB: async (next) => void (db = next),
    now: () => (clock += 1000),
    reseed: applyModuleSeeds,
  })
  return {
    engine,
    get db() {
      return db
    },
    set(next: DB) {
      db = next
    },
  }
}

describe('sync', () => {
  it('pruned template workouts go to the cloud as tombstones and another device drops them', async () => {
    const tripRec = { ...trip(ready()), pauseHomeRoutine: false }
    const base: DB = { ...emptyDB(), trips: [tripRec], workouts: [wo('seed:body:w-2026-10-30-tpl-sex-corrida-longa', '2026-10-30', { modality: 'corrida', templateId: 'seed:body:tpl-sex-corrida-longa' }), wo('w-surf-28', '2026-10-28', { status: 'feito', modality: 'surf' })] }
    const server = createFakePostgrest()
    const a = device(server, base)
    const b = device(server, base)
    expect((await a.engine.uploadAll()).ok).toBe(true)
    await a.engine.sync()
    expect((await b.engine.uploadAll()).ok).toBe(true)
    await b.engine.sync()

    // Device A: she turns travel mode on → the untouched generated workout is removed locally.
    a.set(pruneTravelWorkouts(withTrip(a.db, { pauseHomeRoutine: true })))
    expect(a.db.workouts.map((w) => w.id)).toEqual(['w-surf-28'])
    await a.engine.sync()
    expect(server.userRows('u1').find((r) => r.id === 'seed:body:w-2026-10-30-tpl-sex-corrida-longa')).toMatchObject({ deleted: true })

    await b.engine.sync()
    expect(b.db.workouts.map((w) => w.id)).toEqual(['w-surf-28'])
    // A stale sync never brings it back.
    await a.engine.sync()
    expect(a.db.workouts.map((w) => w.id)).toEqual(['w-surf-28'])
  })
})
